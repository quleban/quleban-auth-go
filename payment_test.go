func TestHallPaymentTokenInterop(t *testing.T) {
	raw, err := os.ReadFile("testdata/payment-token-fixture.json")
	if err != nil {
		t.Fatal(err)
	}
	var fixture struct {
		AppID      string `json:"app_id"`
		AppSecret  string `json:"app_secret"`
		Now        int64  `json:"now"`
		OrderToken string `json:"order_token"`
	}
	if err = json.Unmarshal(raw, &fixture); err != nil {
		t.Fatal(err)
	}
	auth := &QuLeBanAuth{AppID: fixture.AppID, AppSecret: fixture.AppSecret}
	order, err := auth.verifyPaymentOrderAt(fixture.OrderToken, fixture.Now)
	if err != nil {
		t.Fatal(err)
	}
	if order.OrderID != "cross-language-1" || order.UID != "u111" || order.Amount != 10 ||
		order.ActionName != "购买物品" || string(order.ActionData) != `{"item_id":3}` {
		t.Fatalf("unexpected C# order: %+v", order)
	}
}

func TestPaymentUIDUsesCallbackLimit(t *testing.T) {
	a, order := paymentFixture()
	for _, uid := range []string{strings.Repeat("u", 201), strings.Repeat("用", 256), strings.Repeat("😀", 128)} {
		order.UID = uid
		raw, _ := json.Marshal(order)
		got, err := a.verifyPaymentOrderAt(fixturePaymentToken(a, raw), order.CreatedAt)
		if err != nil || got.UID != uid {
			t.Fatalf("callback UID rejected: %v", err)
		}
	}
	for _, uid := range []string{strings.Repeat("u", 257), strings.Repeat("😀", 129), " u", "u ", "u\u0085x"} {
		order.UID = uid
		raw, _ := json.Marshal(order)
		if _, err := a.verifyPaymentOrderAt(fixturePaymentToken(a, raw), order.CreatedAt); err == nil {
			t.Fatal("invalid payment UID accepted")
		}
	}
}
