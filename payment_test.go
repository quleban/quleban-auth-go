func paymentFixture() (*QuLeBanAuth, PaymentOrder) {
	return &QuLeBanAuth{AppID: "qlb_0123456789abcdef0123456789abcdef", AppSecret: base64.RawURLEncoding.EncodeToString(bytes.Repeat([]byte{7}, 32))}, PaymentOrder{
		AppID: "qlb_0123456789abcdef0123456789abcdef", OrderID: "order_123", UID: "111", GameID: "1", RoomID: "12345",
		Amount: 100, Action: "buy_item", ActionName: "购买道具", ActionData: json.RawMessage(`{"item_id":"item_1","quantity":1}`),
		CreatedAt: 1793879700000, ExpireAt: 1793880000000,
	}
}

func fixturePaymentToken(a *QuLeBanAuth, raw []byte) string {
	message := "qlbpay1." + base64.RawURLEncoding.EncodeToString(raw)
	mac := hmac.New(sha256.New, []byte(a.AppSecret))
	mac.Write([]byte(message))
	return message + "." + base64.RawURLEncoding.EncodeToString(mac.Sum(nil))
}

func TestPaymentOrderValidation(t *testing.T) {
	a, order := paymentFixture()
	raw, _ := json.Marshal(order)
	token := fixturePaymentToken(a, raw)
	got, err := a.verifyPaymentOrderAt(token, order.CreatedAt)
	if err != nil || got.Amount != 100 || got.Action != "buy_item" || got.UID != "111" {
		t.Fatalf("valid order: %v", err)
	}
	if _, err = a.verifyPaymentOrderAt(token, order.ExpireAt); !errors.Is(err, ErrPaymentOrderExpired) {
		t.Fatal("expiry boundary")
	}
	for _, mutate := range []func(*PaymentOrder){
		func(v *PaymentOrder) { v.AppID = "qlb_aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa" }, func(v *PaymentOrder) { v.Amount = 0 },
		func(v *PaymentOrder) { v.Amount = 2147483648 }, func(v *PaymentOrder) { v.GameID = "01" }, func(v *PaymentOrder) { v.UID = "" },
		func(v *PaymentOrder) { v.Action = "" }, func(v *PaymentOrder) { v.OrderID = "" }, func(v *PaymentOrder) { v.ActionData = json.RawMessage(`[]`) },
		func(v *PaymentOrder) { v.CreatedAt = v.ExpireAt + 1 },
	} {
		bad := order
		mutate(&bad)
		data, _ := json.Marshal(bad)
		if _, e := a.verifyPaymentOrderAt(fixturePaymentToken(a, data), order.CreatedAt); e == nil {
			t.Fatalf("accepted invalid: %s", data)
		}
	}
	duplicate := strings.Replace(string(raw), `"amount":100`, `"amount":100,"amount":1`, 1)
	if _, e := a.verifyPaymentOrderAt(fixturePaymentToken(a, []byte(duplicate)), order.CreatedAt); e == nil {
		t.Fatal("duplicate amount")
	}
	nested := strings.Replace(string(raw), `"quantity":1`, `"quantity":1,"quantity":2`, 1)
	if _, e := a.verifyPaymentOrderAt(fixturePaymentToken(a, []byte(nested)), order.CreatedAt); e == nil {
		t.Fatal("nested duplicate")
	}
	parts := strings.Split(token, ".")
	parts[1] = base64.RawURLEncoding.EncodeToString([]byte(strings.Replace(string(raw), `"amount":100`, `"amount":1`, 1)))
	if _, e := a.verifyPaymentOrderAt(strings.Join(parts, "."), order.CreatedAt); e == nil {
		t.Fatal("tampered amount")
	}
	wrong := *a
	wrong.AppSecret = base64.RawURLEncoding.EncodeToString(bytes.Repeat([]byte{8}, 32))
	if _, e := wrong.verifyPaymentOrderAt(token, order.CreatedAt); e == nil {
		t.Fatal("wrong key")
	}
}

func TestSignAPIRequestPreservesBodyAndFormat(t *testing.T) {
	a, _ := paymentFixture()
	body := []byte("{\n \"order_id\":\"order_123\", \"amount\":100\n}")
	req, _ := http.NewRequest("POST", "https://hall.invalid/user/app/server/payment/notify", bytes.NewReader(body))
	if err := a.SignAPIRequest(req); err != nil {
		t.Fatal(err)
	}
	match := regexp.MustCompile(`^QuLeBan-Auth app_id="([^"]+)",timestamp="([0-9]+)",nonce="([a-f0-9]+)",signature="([a-f0-9]+)"$`).FindStringSubmatch(req.Header.Get("Authorization"))
	if len(match) != 5 {
		t.Fatal("invalid authorization format")
	}
	mac := hmac.New(sha1.New, []byte(a.AppSecret))
	mac.Write([]byte(match[1] + "\n" + match[2] + "\n" + match[3] + "\n"))
	mac.Write(body)
	mac.Write([]byte("\n"))
	if match[4] != hex.EncodeToString(mac.Sum(nil)) {
		t.Fatal("wrong API signature")
	}
	restored, _ := io.ReadAll(req.Body)
	if !bytes.Equal(restored, body) {
		t.Fatal("body changed")
	}
	if req.Header.Get("Sud-Signature") != "" {
		t.Fatal("callback headers leaked")
	}
}

